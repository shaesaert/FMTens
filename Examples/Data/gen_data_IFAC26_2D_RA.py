#   --mode rt   : VI_mode='rt',   pol_mode='rt',   Δ_VI=δ_rt, Δ_pol=δ_rt
#   --mode apos : VI_mode='apos', pol_mode='apos', Δ_VI=0,    Δ_pol=δ_apos_pol
